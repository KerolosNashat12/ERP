let language = localStorage.getItem('mm.lang') || 'en';

export const getLanguage = () => language;
export const isRtl = () => language === 'ar';

export function setLanguage(next) {
  language = next === 'ar' ? 'ar' : 'en';
  localStorage.setItem('mm.lang', language);
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
}

export function t(key, fallback) {
  return dictionary[language]?.[key] ?? dictionary.en[key] ?? fallback ?? key;
}

/**
 * The same lookup, for a code that arrives from the API in snake_case.
 *
 * Statuses, alert types and enum values are sent the way they are stored —
 * `out_for_delivery`, `low_stock` — while the dictionary above is camelCase
 * throughout. Calling `t()` with the raw code silently returns the code, and
 * because `t()`'s last resort is the key itself the failure looks like a
 * label rather than a miss: the web-orders tiles read OUT_FOR_DELIVERY and
 * NOT_RECEIVED, in Arabic as well as in English, and the dashboard's alerts
 * printed `low stock` under an otherwise perfectly translated title. Nobody
 * noticed for months because a missing translation that prints the key is
 * indistinguishable from a translation somebody wrote badly.
 *
 * So: one conversion, in the one place that owns lookups, and no call site
 * that has to remember the two spellings.
 */
export const tCode = (code, fallback) => t(
  String(code ?? '').replace(/_([a-z])/g, (_, c) => c.toUpperCase()),
  fallback,
);

/**
 * An error from the API, in the language the person is reading.
 *
 * The server speaks English. Every one of its refusals used to arrive on the
 * screen exactly as written — which is how «إنشاء نسخة احتياطية» came to answer
 * an Arabic screen with "Creating a backup is not available on this deployment:
 * the database runs on libsql…". A shop owner photographed it.
 *
 * So an error carries a CODE as well as a sentence, and a code is a thing this
 * dictionary can translate. `{placeholders}` are filled from `error.details`,
 * because "try again in 8 minutes" cannot be assembled out of an English
 * sentence — the number has to arrive as a number.
 *
 * A code nobody has written words for yet falls back to the server's sentence,
 * which is the same trade `tCode()` makes: an English word on the screen is bad,
 * a blank toast where a refusal should be is worse.
 */
/**
 * A business rule, in the reader's own language.
 *
 * Every refusal from the returns and exchange paths carries a `rule` in its
 * details — `return_too_many`, `return_line_done` — and this turns that into a
 * sentence with the numbers filled in. The server's own English text is the
 * fallback, so a rule nobody has written words for yet still says something
 * true rather than nothing at all.
 *
 * Why refusals get this treatment when most errors do not: these are the ones a
 * cashier meets with a customer standing in front of them, and "only 0 of that
 * line remain unreturned" is not a sentence to read out loud in a shop.
 */
