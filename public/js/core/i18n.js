let language = localStorage.getItem('mm.lang') || 'en';

export const getLanguage = () => language;
export const isRtl = () => language === 'ar';

export function setLanguage(next) {
  language = next === 'ar' ? 'ar' : 'en';
  localStorage.setItem('mm.lang', language);
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
}

export function t(key, fallback) {
  return dictionary[language]?.[key] ?? dictionary.en[key] ?? fallback ?? key;
}

/** Choose a record's localised column: pick(row, 'name') -> name_ar || name_en */
export function pick(row, base = 'name') {
  if (!row) return '';
  if (language === 'ar') return row[`${base}_ar`] || row[`${base}_en`] || row[base] || '';
  return row[`${base}_en`] || row[base] || row[`${base}_ar`] || '';
}

